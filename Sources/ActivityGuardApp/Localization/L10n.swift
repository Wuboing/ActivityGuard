    static func tr(_ key: String, _ language: AppLanguage) -> String {
        let dict = language == .chinese ? zh : en
        return dict[key] ?? en[key] ?? key
    }

    static func tr(_ key: String, _ language: AppLanguage, _ args: CVarArg...) -> String {
        let format = tr(key, language)
        return String(format: format, arguments: args)
    }
}

extension AnomalyKind {
    var localizedName: String {
        let key: String
        switch self {
        case .highCPU: key = "high_cpu"
        case .memoryLeak: key = "memory_leak"
        case .zombie: key = "zombie"
        case .highEnergy: key = "high_energy"
        }
        let lang = UserDefaults.standard.string(forKey: "language") ?? "en"
        return L10n.tr(key, AppLanguage(rawValue: lang) ?? .english)
    }
}
